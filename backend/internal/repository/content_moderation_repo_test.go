func TestContentModerationRepositoryEngineMetaInsert(t *testing.T) {
	for _, meta := range []*service.ContentModerationEngineMeta{nil, {Engine: "typesafe", Model: "jev-fixed", RulesVersion: "rules-v1", SkippedImages: 1}} {
		db, mock, err := sqlmock.New()
		require.NoError(t, err)
		args := make([]driver.Value, 29)
		for i := range args {
			args[i] = sqlmock.AnyArg()
		}
		if meta == nil {
			args[25] = nil
		} else {
			args[25] = `{"engine":"typesafe","model":"jev-fixed","rules_version":"rules-v1","skipped_images":1}`
		}
		mock.ExpectQuery("INSERT INTO content_moderation_logs").WithArgs(args...).WillReturnRows(sqlmock.NewRows([]string{"id", "created_at"}).AddRow(1, time.Now()))
		err = NewContentModerationRepository(db).CreateLog(context.Background(), &service.ContentModerationLog{EngineMeta: meta})
		require.NoError(t, err)
		require.NoError(t, mock.ExpectationsWereMet())
		mock.ExpectClose()
		require.NoError(t, db.Close())
	}
}

func TestContentModerationRepositoryEngineMetaRead(t *testing.T) {
	for _, meta := range []any{nil, `{"engine":"typesafe","model":"jev-fixed","rules_version":"rules-v1","skipped_images":1}`} {
		db, mock, err := sqlmock.New()
		require.NoError(t, err)
		mock.ExpectQuery("SELECT COUNT").WillReturnRows(sqlmock.NewRows([]string{"count"}).AddRow(1))
		columns := []string{"id", "request_id", "user_id", "user_email", "api_key_id", "api_key_name", "group_id", "group_name", "endpoint", "provider", "model", "mode", "action", "flagged", "highest_category", "highest_score", "category_scores", "threshold_snapshot", "input_excerpt", "upstream_latency_ms", "error", "violation_count", "auto_banned", "email_sent", "status", "queue_delay_ms", "matched_keyword", "created_at", "engine_meta", "occurred_at", "penalty_scope", "penalty_action", "api_key_locked", "penalty_locked_until"}
		mock.ExpectQuery("SELECT[\\s\\S]*l.engine_meta").WillReturnRows(sqlmock.NewRows(columns).AddRow(1, "req", nil, "", nil, "", nil, "", "/v1/responses", "business", "gpt-model", "observe", "allow", false, "sexual", 0.1, `{"sexual":0.1}`, `{"sexual":0.8}`, "sample", 10, "", 0, false, false, "active", nil, "", time.Now(), meta, time.Now(), "", "", false, nil))
		logs, _, err := NewContentModerationRepository(db).ListLogs(context.Background(), service.ContentModerationLogFilter{})
		require.NoError(t, err)
		require.Len(t, logs, 1)
		require.Equal(t, "gpt-model", logs[0].Model)
		if meta == nil {
			require.Nil(t, logs[0].EngineMeta)
		} else {
			require.Equal(t, "jev-fixed", logs[0].EngineMeta.Model)
			require.Equal(t, 1, logs[0].EngineMeta.SkippedImages)
		}
		require.NoError(t, mock.ExpectationsWereMet())
		mock.ExpectClose()
		require.NoError(t, db.Close())
	}
}

func TestBuildContentModerationLogWhere_BlockedIncludesAllBlockActions(t *testing.T) {
	where, args := buildContentModerationLogWhere(service.ContentModerationLogFilter{Result: "blocked"})

	require.Empty(t, args)
	sql := strings.Join(where, " AND ")
	require.Contains(t, sql, "l.action IN ('block', 'keyword_block', 'hash_block')")
	require.NotContains(t, sql, "l.action = 'block'")
}

func TestCountModerationHitsUsesScopedWindowAndExclusions(t *testing.T) {
	ctx := context.Background()
	now := time.Now()
	user, key := int64(1), int64(2)
	for _, scope := range []string{service.ModerationScopeUser, service.ModerationScopeAPIKey} {
		db, m, err := sqlmock.New()
		require.NoError(t, err)
		defer db.Close()
		m.ExpectBegin()
		tx, err := db.Begin()
		require.NoError(t, err)
		query := "(?s)action <> 'hash_block'.*cyber_log_only.*risk_control_log_only.*action <> 'cyber_policy'.*"
		args := []driver.Value{user, true, now, time.Time{}}
		if scope == service.ModerationScopeAPIKey {
			query += "penalty_scope='api_key'.*api_key_id="
			args = append(args, key)
		} else {
			query += "penalty_scope='user' OR event_id IS NULL"
		}
		m.ExpectQuery(query).WithArgs(args...).WillReturnRows(sqlmock.NewRows([]string{"count"}).AddRow(2))
		n, err := countModerationHits(ctx, tx, &service.ContentModerationLog{UserID: &user, APIKeyID: &key, PenaltyScope: scope}, now, time.Time{}, true)
		require.NoError(t, err)
		require.Equal(t, 2, n)
		m.ExpectRollback()
		require.NoError(t, tx.Rollback())
		require.NoError(t, m.ExpectationsWereMet())
	}
}
