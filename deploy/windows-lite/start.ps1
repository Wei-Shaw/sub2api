function Start-AppOnce {
    Write-Step "Starting Sub2API background process..."
    Repair-ProcessPathEnvironment
    $proc = Start-Process -FilePath $Exe -WorkingDirectory $Runtime -PassThru -WindowStyle Hidden -RedirectStandardOutput $AppOutLog -RedirectStandardError $AppErrLog
    Hide-ProcessWindow $proc.Id
    Set-Content -Path $AppPid -Value $proc.Id -Encoding ASCII
    return $proc
}

function Ensure-AppStarted {
    $proc = Start-AppOnce

    $deadline = (Get-Date).AddSeconds(25)
    while ((Get-Date) -lt $deadline) {
        if (Test-Port "127.0.0.1" $BackendPort) {
            Write-Step "Sub2API is running. PID=$($proc.Id)"
            return
        }

        $proc.Refresh()
        if ($proc.HasExited) {
            Write-Step "Sub2API exited once, retrying after auto-setup..."
            Start-Sleep -Seconds 2
            $proc = Start-AppOnce
        }

        Start-Sleep -Milliseconds 500
    }

    $out = ""
    $err = ""
    if (Test-Path $AppOutLog) { $out = Get-Content $AppOutLog -Tail 80 | Out-String }
    if (Test-Path $AppErrLog) { $err = Get-Content $AppErrLog -Tail 80 | Out-String }
    throw "Sub2API did not open port $BackendPort. STDOUT: $out STDERR: $err"
}

function Start-AdminFrontend {
    if (-not (Test-Path $FrontendServer)) {
        throw "Missing admin frontend server: $FrontendServer"
    }
    if (-not (Test-Path (Join-Path $FrontendDir "index.html"))) {
        Write-Warning "Admin frontend static files were not found at $FrontendDir."
        Write-Warning "If your release package embeds the admin UI in sub2api.exe, you can open http://127.0.0.1:$BackendPort instead."
        return
    }

    $python = Find-Python
    if (-not $python) {
        throw "Python 3 was not found. It is required to serve the admin frontend on port $Port."
    }

    Write-Step "Starting admin frontend on port $Port, proxying API to $BackendPort..."
    $frontendArgs = @($python.Args) + @(
        $FrontendServer,
        "--host", "0.0.0.0",
        "--port", "$Port",
        "--upstream-host", "127.0.0.1",
        "--upstream-port", "$BackendPort",
        "--frontend-dir", $FrontendDir
    )
    $proc = Start-Process -FilePath $python.File -ArgumentList $frontendArgs -WorkingDirectory $Runtime -PassThru -WindowStyle Hidden -RedirectStandardOutput $FrontendOutLog -RedirectStandardError $FrontendErrLog
    Hide-ProcessWindow $proc.Id
    Set-Content -Path $FrontendPid -Value $proc.Id -Encoding ASCII

    if (-not (Wait-Port "127.0.0.1" $Port 10)) {
        $err = ""
        if (Test-Path $FrontendErrLog) { $err = Get-Content $FrontendErrLog -Tail 40 | Out-String }
        throw "Admin frontend did not open port $Port. $err"
    }

    Write-Step "Admin frontend is running. PID=$($proc.Id)"
}

