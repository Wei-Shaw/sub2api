        <div class="hidden lg:block">
          <h1 class="truncate text-h2 font-bold text-fg">
            {{ pageTitle }}
          </h1>
          <p v-if="pageDescription" class="truncate text-meta text-fg-muted">
            {{ pageDescription }}
          </p>
