import { ref } from 'vue'
import { useAppStore } from '@/stores/app'
import { adminAPI } from '@/api/admin'

export type AddMethod = 'oauth' | 'setup-token'
export type AuthInputMethod =
  | 'manual'
  | 'cookie'
  | 'refresh_token'
  | 'mobile_refresh_token'
  | 'session_token'
  | 'access_token'
  | 'codex_session'
  | 'agent_identity'
  | 'codex_pat'
  | 'sso_cookie'
  | 'email_password'

export interface OAuthState {
  authUrl: string
  authCode: string
  sessionId: string
  sessionKey: string
  loading: boolean
  error: string
}

export interface TokenInfo {
  org_uuid?: string
  account_uuid?: string
  email_address?: string
  [key: string]: unknown
}

const CLAUDE_SETUP_TOKEN_PREFIX = 'sk-ant-oat01-'

export const parseClaudeSetupTokens = (input: string): string[] => {
  return input
    .split('\n')
    .map((token) => token.trim())
    .filter(Boolean)
}

export const buildClaudeSetupTokenCredentials = (rawToken: string): TokenInfo => {
  const accessToken = rawToken.trim()
  if (!accessToken.startsWith(CLAUDE_SETUP_TOKEN_PREFIX) || /\s/.test(accessToken)) {
    throw new Error('Invalid Claude setup token')
  }

  // `claude setup-token` produces a long-lived, inference-only bearer token.
  // Do not add expires_at/refresh_token: direct setup tokens are not refreshed by Sub2API.
  return {
    access_token: accessToken,
    token_type: 'Bearer',
    scope: 'user:inference'
  }
}

export function useAccountOAuth() {
  const appStore = useAppStore()

  // State
  const authUrl = ref('')
  const authCode = ref('')
  const sessionId = ref('')
  const sessionKey = ref('')
  const loading = ref(false)
  const error = ref('')

  // Reset state
  const resetState = () => {
    authUrl.value = ''
    authCode.value = ''
    sessionId.value = ''
    sessionKey.value = ''
    loading.value = false
    error.value = ''
  }

  // Generate auth URL
  const generateAuthUrl = async (
    addMethod: AddMethod,
    proxyId?: number | null
  ): Promise<boolean> => {
    if (addMethod === 'setup-token') {
      error.value = 'Paste the token generated by claude setup-token'
      return false
    }

    loading.value = true
    authUrl.value = ''
    sessionId.value = ''
    error.value = ''

    try {
      const proxyConfig = proxyId ? { proxy_id: proxyId } : {}
      const response = await adminAPI.accounts.generateAuthUrl('/admin/accounts/generate-auth-url', proxyConfig)
      authUrl.value = response.auth_url
      sessionId.value = response.session_id
      return true
    } catch (err: any) {
      error.value = err.response?.data?.detail || 'Failed to generate auth URL'
      appStore.showError(error.value)
      return false
    } finally {
      loading.value = false
    }
  }

  // Exchange auth code for tokens
  const exchangeAuthCode = async (
    addMethod: AddMethod,
    proxyId?: number | null
  ): Promise<TokenInfo | null> => {
    if (addMethod === 'setup-token') {
      error.value = 'Paste the token generated by claude setup-token'
      return null
    }

    if (!authCode.value.trim() || !sessionId.value) {
      error.value = 'Missing auth code or session ID'
      return null
    }

    loading.value = true
    error.value = ''

    try {
      const proxyConfig = proxyId ? { proxy_id: proxyId } : {}
      const tokenInfo = await adminAPI.accounts.exchangeCode('/admin/accounts/exchange-code', {
        session_id: sessionId.value,
        code: authCode.value.trim(),
        ...proxyConfig
      })

      return tokenInfo as TokenInfo
    } catch (err: any) {
      error.value = err.response?.data?.detail || 'Failed to exchange auth code'
      appStore.showError(error.value)
      return null
    } finally {
      loading.value = false
    }
  }

  // Cookie-based authentication
  const cookieAuth = async (
    addMethod: AddMethod,
    sessionKeyValue: string,
    proxyId?: number | null
  ): Promise<TokenInfo | null> => {
    if (!sessionKeyValue.trim()) {
      error.value = 'Please enter sessionKey'
      return null
    }

    loading.value = true
    error.value = ''

    try {
      if (addMethod === 'setup-token') {
        return buildClaudeSetupTokenCredentials(sessionKeyValue)
      }

      const proxyConfig = proxyId ? { proxy_id: proxyId } : {}
      const tokenInfo = await adminAPI.accounts.exchangeCode('/admin/accounts/cookie-auth', {
        session_id: '',
        code: sessionKeyValue.trim(),
        ...proxyConfig
      })

      return tokenInfo as TokenInfo
    } catch (err: any) {
      error.value = err.response?.data?.detail || 'Cookie authorization failed'
      return null
    } finally {
      loading.value = false
    }
  }

  // Parse line-separated secret values (session keys or direct setup tokens).
  const parseSessionKeys = (input: string): string[] => {
    return parseClaudeSetupTokens(input)
  }

  // Build extra info from token response
  const buildExtraInfo = (tokenInfo: TokenInfo): Record<string, string> | undefined => {
    const extra: Record<string, string> = {}
    if (tokenInfo.org_uuid) {
      extra.org_uuid = tokenInfo.org_uuid
    }
    if (tokenInfo.account_uuid) {
      extra.account_uuid = tokenInfo.account_uuid
    }
    if (tokenInfo.email_address) {
      extra.email_address = tokenInfo.email_address
    }
    return Object.keys(extra).length > 0 ? extra : undefined
  }

  return {
    // State
    authUrl,
    authCode,
    sessionId,
    sessionKey,
    loading,
    error,
    // Methods
    resetState,
    generateAuthUrl,
    exchangeAuthCode,
    cookieAuth,
    parseSessionKeys,
    buildClaudeSetupTokenCredentials,
    buildExtraInfo
  }
}
