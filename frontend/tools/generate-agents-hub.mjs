import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const owner = 'msitarzewski'
const repo = 'agency-agents'
const branch = 'main'
const repoUrl = `https://github.com/${owner}/${repo}`
const apiTreeUrl = `https://api.github.com/repos/${owner}/${repo}/git/trees/${branch}?recursive=1`
const rawBaseUrl = `https://raw.githubusercontent.com/${owner}/${repo}/${branch}`

const categoryLabelsZh = {
  academic: '学术研究',
  design: '设计',
  engineering: '工程',
  finance: '财务',
  'game-development': '游戏开发',
  marketing: '营销增长',
  'paid-media': '付费投放',
  product: '产品',
  'project-management': '项目管理',
  sales: '销售',
  'spatial-computing': '空间计算',
  specialized: '专项能力',
  strategy: '战略',
  support: '客户支持',
  testing: '测试验证',
}

const allowedCategories = Object.keys(categoryLabelsZh)

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const outputPath = path.resolve(__dirname, '../src/data/agentHub.generated.ts')

async function main() {
  const treeResponse = await fetch(apiTreeUrl, {
    headers: {
      Accept: 'application/vnd.github+json',
      'User-Agent': 'sub2api-agents-hub-generator',
    },
  })

  if (!treeResponse.ok) {
    throw new Error(`Failed to fetch GitHub tree: ${treeResponse.status} ${treeResponse.statusText}`)
  }

  const tree = await treeResponse.json()
  const markdownFiles = tree.tree
    .filter((item) => item.type === 'blob')
    .filter((item) => item.path.endsWith('.md'))
    .filter((item) => {
      const [category, fileName] = item.path.split('/')
      return allowedCategories.includes(category) && fileName && fileName.toLowerCase() !== 'readme.md'
    })
    .sort((a, b) => a.path.localeCompare(b.path))

  const agents = await mapWithConcurrency(markdownFiles, 10, async (file) => {
    const rawMarkdown = await fetchText(`${rawBaseUrl}/${encodeURI(file.path)}`)
    const frontmatter = parseFrontmatter(rawMarkdown)
    const division = file.path.split('/')[0]
    const name = frontmatter.name || titleFromPath(file.path)
    const descriptionEn = frontmatter.description || firstMarkdownParagraph(rawMarkdown)

    return {
      id: slugify(file.path.replace(/\.md$/i, '')),
      name,
      division,
      sourcePath: file.path,
      sourceUrl: `${repoUrl}/blob/${branch}/${file.path}`,
      emoji: frontmatter.emoji || 'AI',
      color: normalizeColor(frontmatter.color),
      descriptionEn,
      summaryZh: buildChineseSummary({ name, division, description: descriptionEn }),
      vibeEn: frontmatter.vibe || '',
      rawMarkdown,
    }
  })

  const categories = [...new Set(agents.map((agent) => agent.division))]
  const generated = [
    '/* eslint-disable */',
    '// This file is generated by frontend/tools/generate-agents-hub.mjs.',
    '// Do not edit by hand; rerun the script to refresh the snapshot.',
    '',
    'export type AgentHubItem = {',
    '  id: string',
    '  name: string',
    '  division: string',
    '  sourcePath: string',
    '  sourceUrl: string',
    '  emoji: string',
    '  color: string',
    '  descriptionEn: string',
    '  summaryZh: string',
    '  vibeEn: string',
    '  rawMarkdown: string',
    '}',
    '',
    'export const AGENTS_HUB_SOURCE = ' + JSON.stringify({
      repo: `${owner}/${repo}`,
      repoUrl,
      branch,
      commit: tree.sha,
      generatedAt: new Date().toISOString(),
      license: 'MIT',
      licenseUrl: `${repoUrl}/blob/${branch}/LICENSE`,
      totalAgents: agents.length,
      totalDivisions: categories.length,
    }, null, 2) + ' as const',
    '',
    'export const AGENTS_HUB_DIVISIONS = ' + JSON.stringify(categories, null, 2) + ' as const',
    '',
    'export const AGENTS_HUB_ITEMS: AgentHubItem[] = ' + JSON.stringify(agents, null, 2),
    '',
  ].join('\n')

  await mkdir(path.dirname(outputPath), { recursive: true })
  await writeFile(outputPath, generated, 'utf8')

  console.log(`Generated ${agents.length} agents across ${categories.length} divisions`)
  console.log(`Source commit: ${tree.sha}`)
  console.log(outputPath)
}

async function fetchText(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'sub2api-agents-hub-generator' } })
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`)
  }
  return response.text()
}

async function mapWithConcurrency(items, concurrency, mapper) {
  const results = new Array(items.length)
  let index = 0

  async function worker() {
    while (index < items.length) {
      const currentIndex = index
      index += 1
      results[currentIndex] = await mapper(items[currentIndex], currentIndex)
    }
  }

  await Promise.all(Array.from({ length: Math.min(concurrency, items.length) }, worker))
  return results
}

function parseFrontmatter(markdown) {
  if (!markdown.startsWith('---')) return {}

  const end = markdown.indexOf('\n---', 3)
  if (end === -1) return {}

  const frontmatter = markdown.slice(3, end).trim()
  const values = {}
  for (const line of frontmatter.split('\n')) {
    const match = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/)
    if (!match) continue
    values[match[1]] = stripQuotes(match[2].trim())
  }
  return values
}

function stripQuotes(value) {
  if (!value) return ''
  if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
    return value.slice(1, -1)
  }
  return value
}

function firstMarkdownParagraph(markdown) {
  return markdown
    .replace(/^---[\s\S]*?\n---/, '')
    .split('\n')
    .map((line) => line.trim())
    .find((line) => line && !line.startsWith('#') && !line.startsWith('-')) || ''
}

function titleFromPath(sourcePath) {
  return path
    .basename(sourcePath, '.md')
    .replace(/^[a-z]+-/, '')
    .split(/[-_]+/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ')
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

function normalizeColor(color) {
  if (/^#[0-9a-f]{6}$/i.test(color || '')) return color
  return '#006fd6'
}

function buildChineseSummary({ name, division, description }) {
  const label = categoryLabelsZh[division] || division
  const focus = normalizeDescriptionFocus(description)
  if (!focus) {
    return `${label}方向的专业 Agent，适合复制完整 Markdown 后按具体工作流改造使用。`
  }
  return `${label}方向的专业 Agent，聚焦 ${focus}。`
}

function normalizeDescriptionFocus(description) {
  return description
    .replace(/\s+/g, ' ')
    .replace(/^Expert\s+/i, '')
    .replace(/^Senior\s+/i, '')
    .replace(/^Full-stack\s+/i, '')
    .replace(/^Full-spectrum\s+/i, '')
    .replace(/^Specialized\s+/i, '')
    .replace(/^Specialist\s+(in|for)\s+/i, '')
    .replace(/^Autonomous\s+/i, '')
    .replace(/^AI agent\s+(that|who)\s+/i, '')
    .replace(/^in\s+/i, '')
    .replace(/\.$/, '')
    .slice(0, 180)
    .trim()
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
