// Command gen-frontend-constants 把 plugins/channel-management/service 里的
// 权威枚举常量（BillingMode* / Status* / Platform* / BillingModelSource*）
// 渲染成前端 TS 常量文件。让常量单一来源（service.go），前端不再独立维护
// 漂移容易的字符串。
//
// 使用：
//
//	cd plugins/channel-management
//	go generate ./service/...
//
// 或直接：
//
//	go run ./cmd/gen-frontend-constants -out frontend/src/utils/channelConstants.ts
//
// 工程原则：复用 service.BillingModes() 等 List 函数；解耦 handler/repo；
// enumGroup 抽象让新增枚举只追加一组数据（参考 CLAUDE.md）。
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/Wei-Shaw/sub2api/plugins/channel-management/service"
)

// enumGroup 描述一组枚举：常量族（每个值独立 export）+ 数组 + TS 联合类型。
// 模板循环渲染每组，避免硬编码三遍 BillingMode / Status / BillingModelSource
// 的样板代码（抽象原则）。
type enumGroup struct {
	TSTypeName  string // TS 联合类型名，如 "BillingMode"
	ConstPrefix string // 单值常量前缀，如 "BILLING_MODE_"
	ArrayName   string // 数组常量名，如 "BILLING_MODES"
	Comment     string // 写到该组上方的中文注释
	Values      []enumValue
}

type enumValue struct {
	Suffix  string // 拼到 ConstPrefix 后构成常量名，如 "TOKEN" → "BILLING_MODE_TOKEN"
	Literal string // TS 字面量值，如 "token"
}

// collectGroups 从 service 包常量收集所有枚举组。新增枚举只在这里追加一组。
func collectGroups() []enumGroup {
	return []enumGroup{
		{
			TSTypeName:  "BillingMode",
			ConstPrefix: "BILLING_MODE_",
			ArrayName:   "BILLING_MODES",
			Comment:     "Billing mode — 与 service.BillingMode* 对齐。",
			Values: []enumValue{
				{Suffix: "TOKEN", Literal: string(service.BillingModeToken)},
				{Suffix: "PER_REQUEST", Literal: string(service.BillingModePerRequest)},
				{Suffix: "IMAGE", Literal: string(service.BillingModeImage)},
			},
		},
		{
			TSTypeName:  "ChannelStatus",
			ConstPrefix: "CHANNEL_STATUS_",
			ArrayName:   "CHANNEL_STATUSES",
			Comment:     "Channel status — 与 service.StatusActive / StatusDisabled 对齐。",
			Values: []enumValue{
				{Suffix: "ACTIVE", Literal: service.StatusActive},
				{Suffix: "DISABLED", Literal: service.StatusDisabled},
			},
		},
		{
			TSTypeName:  "Platform",
			ConstPrefix: "PLATFORM_",
			ArrayName:   "PLATFORMS",
			Comment:     "Platform — 与 service.Platform* 对齐。",
			Values: []enumValue{
				{Suffix: "ANTHROPIC", Literal: service.PlatformAnthropic},
				{Suffix: "OPENAI", Literal: service.PlatformOpenAI},
				{Suffix: "GEMINI", Literal: service.PlatformGemini},
				{Suffix: "ANTIGRAVITY", Literal: service.PlatformAntigravity},
			},
		},
		{
			TSTypeName:  "BillingModelSource",
			ConstPrefix: "BILLING_MODEL_SOURCE_",
			ArrayName:   "BILLING_MODEL_SOURCES",
			Comment:     "Billing model source — 与 service.BillingModelSource* 对齐。",
			Values: []enumValue{
				{Suffix: "REQUESTED", Literal: service.BillingModelSourceRequested},
				{Suffix: "UPSTREAM", Literal: service.BillingModelSourceUpstream},
				{Suffix: "CHANNEL_MAPPED", Literal: service.BillingModelSourceChannelMapped},
			},
		},
	}
}

// validateAgainstService 把 collectGroups() 与 service 包 List 函数交叉比对。
// 后端新增枚举值但 codegen 没跟进时立刻报错，避免悄悄生成不全的 TS。
func validateAgainstService(groups []enumGroup) error {
	checks := []struct {
		name     string
		expected []string
		actual   []string
	}{
		{"BillingMode", findGroup(groups, "BillingMode").literals(), service.BillingModes()},
		{"ChannelStatus", findGroup(groups, "ChannelStatus").literals(), service.ChannelStatuses()},
		{"Platform", findGroup(groups, "Platform").literals(), service.Platforms()},
		{"BillingModelSource", findGroup(groups, "BillingModelSource").literals(), service.BillingModelSources()},
	}
	for _, c := range checks {
		if !sameStringSet(c.expected, c.actual) {
			return fmt.Errorf("group %s drifted: codegen=%v service=%v",
				c.name, c.expected, c.actual)
		}
	}
	return nil
}

func findGroup(groups []enumGroup, tsTypeName string) enumGroup {
	for _, g := range groups {
		if g.TSTypeName == tsTypeName {
			return g
		}
	}
	return enumGroup{}
}

func (g enumGroup) literals() []string {
	out := make([]string, len(g.Values))
	for i, v := range g.Values {
		out[i] = v.Literal
	}
	return out
}

func sameStringSet(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	set := make(map[string]struct{}, len(a))
	for _, s := range a {
		set[s] = struct{}{}
	}
	for _, s := range b {
		if _, ok := set[s]; !ok {
			return false
		}
	}
	return true
}

const headerTpl = `// Code generated by gen-frontend-constants; DO NOT EDIT.
//
// Source: plugins/channel-management/service/channel.go
// Run: cd plugins/channel-management && go generate ./...
//
// 修改后端 service 包的枚举常量（BillingMode* / Status* / Platform* /
// BillingModelSource*）后，重新运行上述命令同步本文件。
//
// 校验路径：codegen 工具在生成前会调用 service.BillingModes() 等 List
// 函数交叉比对，缺枚举值会直接报错。
`

const groupTpl = `
// {{.Comment}}
{{range .Values}}export const {{$.ConstPrefix}}{{.Suffix}} = '{{.Literal}}' as const
{{end}}export type {{.TSTypeName}} =
{{range $i, $v := .Values}}{{if $i}}
{{end}}  | typeof {{$.ConstPrefix}}{{$v.Suffix}}{{end}}

export const {{.ArrayName}}: ReadonlyArray<{{.TSTypeName}}> = [
{{range .Values}}  {{$.ConstPrefix}}{{.Suffix}},
{{end}}] as const
`

// render 把所有枚举组渲染成最终 TS 文件内容。
//
// 实现说明：拆成两个模板（header + per-group）避免在嵌套 range 里拿外层
// group 字段的限制。每组渲染时 $ 指向 group 本身，能直接访问 ConstPrefix。
func render(groups []enumGroup) (string, error) {
	var sb strings.Builder
	sb.WriteString(headerTpl)
	tpl, err := template.New("g").Parse(groupTpl)
	if err != nil {
		return "", err
	}
	for _, g := range groups {
		if err := tpl.Execute(&sb, g); err != nil {
			return "", err
		}
	}
	return sb.String(), nil
}

// writeFile 创建父目录后写入。
func writeFile(path, body string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(body), 0o644)
}

func main() {
	out := flag.String("out", "frontend/src/utils/channelConstants.ts",
		"output path (relative to plugins/channel-management)")
	flag.Parse()

	groups := collectGroups()
	if err := validateAgainstService(groups); err != nil {
		log.Fatalf("gen-frontend-constants: %v", err)
	}
	body, err := render(groups)
	if err != nil {
		log.Fatalf("gen-frontend-constants: render failed: %v", err)
	}
	if err := writeFile(*out, body); err != nil {
		log.Fatalf("gen-frontend-constants: write %s failed: %v", *out, err)
	}
}
